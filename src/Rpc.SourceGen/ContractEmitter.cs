using System.Linq;
using System.Text;

namespace Rpc.SourceGen;

internal static class ContractEmitter
{
    private const string GeneratorVersion = "1.0.0";

    public static string Emit(ContractModel contract)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//     by Rpc.SourceGen v{GeneratorVersion}. Do not edit.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1591");
        sb.AppendLine();

        var generatedNamespace = string.IsNullOrEmpty(contract.Namespace)
            ? "RpcGenerated"
            : contract.Namespace + ".Generated";
        sb.AppendLine($"namespace {generatedNamespace};");
        sb.AppendLine();

        EmitArgsRecords(sb, contract);
        EmitProxy(sb, contract);
        sb.AppendLine();
        EmitDispatcher(sb, contract);
        sb.AppendLine();
        EmitExtensions(sb, contract);

        return sb.ToString();
    }

    // -- args records ------------------------------------------------------

    private static void EmitArgsRecords(StringBuilder sb, ContractModel contract)
    {
        foreach (var method in contract.Methods)
        {
            if (method.ValueParameters.Count <= 1) continue;
            // For methods with the duplex/stream initial value being the FIRST param, we still
            // serialize a single arg payload (initial) — but for multi-arg methods, use a record.
            sb.Append("internal sealed record ");
            sb.Append(ArgsRecordName(contract, method));
            sb.Append('(');
            sb.Append(string.Join(", ",
                method.ValueParameters.Select(p => $"{p.FullTypeName} {Pascal(p.Name)}")));
            sb.AppendLine(");");
            sb.AppendLine();
        }
    }

    private static string ArgsRecordName(ContractModel c, MethodModel m) =>
        $"__{c.InterfaceShortName}_{m.Name}_Args";

    // -- proxy -------------------------------------------------------------

    private static void EmitProxy(StringBuilder sb, ContractModel contract)
    {
        sb.AppendLine("/// <summary>Auto-generated RpcKit proxy. See Rpc.SourceGen.</summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rpc.SourceGen\", \"{GeneratorVersion}\")]");
        sb.AppendLine($"public sealed class {contract.ProxyClassName} : {contract.InterfaceFullName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string ContractId = \"{contract.InterfaceShortName}\";");
        sb.AppendLine();
        sb.AppendLine("    private readonly global::Rpc.Core.IRpcInvoker __invoker;");
        sb.AppendLine("    private readonly global::Rpc.Core.RpcAddress __address;");
        sb.AppendLine();
        sb.AppendLine($"    public {contract.ProxyClassName}(global::Rpc.Core.IRpcInvoker invoker, global::Rpc.Core.RpcAddress address)");
        sb.AppendLine("    {");
        sb.AppendLine("        this.__invoker = invoker;");
        sb.AppendLine("        this.__address = address;");
        sb.AppendLine("    }");

        foreach (var m in contract.Methods)
        {
            sb.AppendLine();
            EmitProxyMethod(sb, contract, m);
        }

        sb.AppendLine("}");
    }

    private static void EmitProxyMethod(StringBuilder sb, ContractModel c, MethodModel m)
    {
        var ctParamName = m.CancellationTokenParamName;
        var renderedParams = string.Join(", ",
            m.ValueParameters.Select(p => $"{p.FullTypeName} {p.Name}")
            .Concat(m.HasCancellationToken
                ? new[] { $"global::System.Threading.CancellationToken {ctParamName} = default" }
                : System.Array.Empty<string>()));

        var ctArg = m.HasCancellationToken ? ctParamName : "default";
        var exclusiveArg = m.Exclusive ? "true" : "false";

        switch (m.Kind)
        {
            case MethodKind.InvokeResult:
                sb.AppendLine($"    public async {m.ReturnTypeRendered} {m.Name}({renderedParams})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var __payload = {SerializePayload(c, m)};");
                sb.AppendLine($"        var __result = await __invoker.InvokeAsync(__address, ContractId, {m.MethodId}, __payload, exclusive: {exclusiveArg}, cancellationToken: {ctArg}).ConfigureAwait(false);");
                sb.AppendLine($"        return global::System.Text.Json.JsonSerializer.Deserialize<{m.ResultElementTypeFullName}>(__result!, global::Rpc.Core.RpcJson.Options)!;");
                sb.AppendLine("    }");
                break;

            case MethodKind.InvokeVoid:
                sb.AppendLine($"    public async {m.ReturnTypeRendered} {m.Name}({renderedParams})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var __payload = {SerializePayload(c, m)};");
                sb.AppendLine($"        await __invoker.InvokeAsync(__address, ContractId, {m.MethodId}, __payload, exclusive: {exclusiveArg}, cancellationToken: {ctArg}).ConfigureAwait(false);");
                sb.AppendLine("    }");
                break;

            case MethodKind.Stream:
                sb.AppendLine($"    public {m.ReturnTypeRendered} {m.Name}({renderedParams})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var __payload = {SerializePayload(c, m)};");
                sb.AppendLine($"        return IterateAsync({ctArg});");
                sb.AppendLine($"        async {m.ReturnTypeRendered} IterateAsync(global::System.Threading.CancellationToken __ct)");
                sb.AppendLine("        {");
                sb.AppendLine($"            await foreach (var __chunk in __invoker.OpenStreamAsync(__address, ContractId, {m.MethodId}, __payload, exclusive: {exclusiveArg}, cancellationToken: __ct).WithCancellation(__ct).ConfigureAwait(false))");
                sb.AppendLine("            {");
                sb.AppendLine($"                var __value = global::System.Text.Json.JsonSerializer.Deserialize<{m.ResultElementTypeFullName}>(__chunk, global::Rpc.Core.RpcJson.Options);");
                sb.AppendLine("                if (__value is not null) yield return __value;");
                sb.AppendLine("            }");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                break;

            case MethodKind.Duplex:
                sb.AppendLine($"    public {m.ReturnTypeRendered} {m.Name}({renderedParams})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var __payload = {SerializePayload(c, m)};");
                sb.AppendLine($"        var __openTask = __invoker.OpenDuplexAsync(__address, ContractId, {m.MethodId}, __payload, exclusive: {exclusiveArg}, cancellationToken: {ctArg});");
                sb.AppendLine($"        return new global::Rpc.Core.DeferredDuplexCall<{m.DuplexUpFullName}, {m.DuplexDownFullName}>(__openTask);");
                sb.AppendLine("    }");
                break;
        }
    }

    private static string SerializePayload(ContractModel c, MethodModel m)
    {
        if (m.ValueParameters.Count == 0)
            return "\"{}\"";
        if (m.ValueParameters.Count == 1)
            return $"global::System.Text.Json.JsonSerializer.Serialize({m.ValueParameters[0].Name}, global::Rpc.Core.RpcJson.Options)";
        // N args — wrap into args record
        var argsName = ArgsRecordName(c, m);
        var argList = string.Join(", ", m.ValueParameters.Select(p => p.Name));
        return $"global::System.Text.Json.JsonSerializer.Serialize(new {argsName}({argList}), global::Rpc.Core.RpcJson.Options)";
    }

    // -- dispatcher --------------------------------------------------------

    private static void EmitDispatcher(StringBuilder sb, ContractModel contract)
    {
        sb.AppendLine("/// <summary>Auto-generated dispatcher. See Rpc.SourceGen.</summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rpc.SourceGen\", \"{GeneratorVersion}\")]");
        sb.AppendLine($"public static class {contract.DispatcherClassName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string ContractId = \"{contract.InterfaceShortName}\";");
        sb.AppendLine();
        sb.AppendLine($"    public static void Register(global::Rpc.Core.IDispatcherRegistry registry, {contract.InterfaceFullName} implementation)");
        sb.AppendLine("    {");
        foreach (var m in contract.Methods)
        {
            EmitDispatcherRegistration(sb, contract, m);
        }
        sb.AppendLine("    }");

        // emit private helpers used by Register
        foreach (var m in contract.Methods)
        {
            if (m.Kind == MethodKind.Stream) EmitStreamHelper(sb, contract, m);
        }

        sb.AppendLine("}");
    }

    private static void EmitDispatcherRegistration(StringBuilder sb, ContractModel c, MethodModel m)
    {
        switch (m.Kind)
        {
            case MethodKind.InvokeResult:
                sb.AppendLine($"        registry.RegisterInvoke(ContractId, {m.MethodId}, async (__payloadJson, __ct) =>");
                sb.AppendLine("        {");
                EmitDeserializeArgs(sb, c, m, indent: "            ");
                sb.Append($"            var __result = await implementation.{m.Name}(");
                sb.Append(BuildImplCallArgs(m, ctName: "__ct"));
                sb.AppendLine(").ConfigureAwait(false);");
                sb.AppendLine("            return global::System.Text.Json.JsonSerializer.Serialize(__result, global::Rpc.Core.RpcJson.Options);");
                sb.AppendLine("        });");
                break;

            case MethodKind.InvokeVoid:
                sb.AppendLine($"        registry.RegisterInvoke(ContractId, {m.MethodId}, async (__payloadJson, __ct) =>");
                sb.AppendLine("        {");
                EmitDeserializeArgs(sb, c, m, indent: "            ");
                sb.Append($"            await implementation.{m.Name}(");
                sb.Append(BuildImplCallArgs(m, ctName: "__ct"));
                sb.AppendLine(").ConfigureAwait(false);");
                sb.AppendLine("            return null;");
                sb.AppendLine("        });");
                break;

            case MethodKind.Stream:
                sb.AppendLine($"        registry.RegisterStream(ContractId, {m.MethodId}, (__payloadJson, __ct) => Stream_{m.Name}(implementation, __payloadJson, __ct));");
                break;

            case MethodKind.Duplex:
                sb.AppendLine($"        registry.RegisterDuplex(ContractId, {m.MethodId}, async (__initialJson, __upstream, __downstream, __ct) =>");
                sb.AppendLine("        {");
                EmitDeserializeArgsForDuplex(sb, c, m, indent: "            ");
                sb.Append("            await using var __typedCall = implementation.");
                sb.Append(m.Name);
                sb.Append('(');
                sb.Append(BuildImplCallArgs(m, ctName: "__ct"));
                sb.AppendLine(");");
                sb.AppendLine();
                sb.AppendLine("            var __pumpUp = global::System.Threading.Tasks.Task.Run(async () =>");
                sb.AppendLine("            {");
                sb.AppendLine("                try");
                sb.AppendLine("                {");
                sb.AppendLine("                    await foreach (var __json in __upstream.ReadAllAsync(__ct).ConfigureAwait(false))");
                sb.AppendLine("                    {");
                sb.AppendLine($"                        var __resp = global::System.Text.Json.JsonSerializer.Deserialize<{m.DuplexUpFullName}>(__json, global::Rpc.Core.RpcJson.Options);");
                sb.AppendLine("                        if (__resp is not null) await __typedCall.SendAsync(__resp, __ct).ConfigureAwait(false);");
                sb.AppendLine("                    }");
                sb.AppendLine("                }");
                sb.AppendLine("                catch (global::System.OperationCanceledException) { /* expected on cancel */ }");
                sb.AppendLine("                finally { await __typedCall.CompleteAsync().ConfigureAwait(false); }");
                sb.AppendLine("            }, __ct);");
                sb.AppendLine();
                sb.AppendLine("            try");
                sb.AppendLine("            {");
                sb.AppendLine("                await foreach (var __ev in __typedCall.Responses.WithCancellation(__ct).ConfigureAwait(false))");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var __json = global::System.Text.Json.JsonSerializer.Serialize<{m.DuplexDownFullName}>(__ev, global::Rpc.Core.RpcJson.Options);");
                sb.AppendLine("                    await __downstream.WriteAsync(__json, __ct).ConfigureAwait(false);");
                sb.AppendLine("                }");
                sb.AppendLine("            }");
                sb.AppendLine("            finally");
                sb.AppendLine("            {");
                sb.AppendLine("                try { await __pumpUp.ConfigureAwait(false); } catch { /* surfaced via cancellation */ }");
                sb.AppendLine("            }");
                sb.AppendLine("        });");
                break;
        }
    }

    private static void EmitStreamHelper(StringBuilder sb, ContractModel c, MethodModel m)
    {
        sb.AppendLine();
        sb.AppendLine($"    private static async global::System.Collections.Generic.IAsyncEnumerable<string> Stream_{m.Name}({c.InterfaceFullName} implementation, string __payloadJson, [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken __ct)");
        sb.AppendLine("    {");
        EmitDeserializeArgs(sb, c, m, indent: "        ");
        sb.Append($"        await foreach (var __item in implementation.{m.Name}(");
        sb.Append(BuildImplCallArgs(m, ctName: "__ct"));
        sb.AppendLine(").WithCancellation(__ct).ConfigureAwait(false))");
        sb.AppendLine("        {");
        sb.AppendLine($"            yield return global::System.Text.Json.JsonSerializer.Serialize(__item, global::Rpc.Core.RpcJson.Options);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void EmitDeserializeArgs(StringBuilder sb, ContractModel c, MethodModel m, string indent)
    {
        if (m.ValueParameters.Count == 0)
        {
            // nothing to deserialize
            return;
        }
        if (m.ValueParameters.Count == 1)
        {
            var p = m.ValueParameters[0];
            sb.AppendLine($"{indent}var __arg0 = global::System.Text.Json.JsonSerializer.Deserialize<{p.FullTypeName}>(__payloadJson, global::Rpc.Core.RpcJson.Options)!;");
            return;
        }
        // multiple args
        var argsName = ArgsRecordName(c, m);
        sb.AppendLine($"{indent}var __args = global::System.Text.Json.JsonSerializer.Deserialize<{argsName}>(__payloadJson, global::Rpc.Core.RpcJson.Options)!;");
    }

    private static void EmitDeserializeArgsForDuplex(StringBuilder sb, ContractModel c, MethodModel m, string indent)
    {
        // For duplex, the initial payload is read from __initialJson (not __payloadJson)
        if (m.ValueParameters.Count == 0) return;
        if (m.ValueParameters.Count == 1)
        {
            var p = m.ValueParameters[0];
            sb.AppendLine($"{indent}var __arg0 = global::System.Text.Json.JsonSerializer.Deserialize<{p.FullTypeName}>(__initialJson, global::Rpc.Core.RpcJson.Options)!;");
            return;
        }
        var argsName = ArgsRecordName(c, m);
        sb.AppendLine($"{indent}var __args = global::System.Text.Json.JsonSerializer.Deserialize<{argsName}>(__initialJson, global::Rpc.Core.RpcJson.Options)!;");
    }

    private static string BuildImplCallArgs(MethodModel m, string ctName)
    {
        var argRefs = new System.Collections.Generic.List<string>();
        if (m.ValueParameters.Count == 1)
        {
            argRefs.Add("__arg0");
        }
        else if (m.ValueParameters.Count > 1)
        {
            for (int i = 0; i < m.ValueParameters.Count; i++)
                argRefs.Add($"__args.{Pascal(m.ValueParameters[i].Name)}");
        }
        if (m.HasCancellationToken) argRefs.Add(ctName);
        return string.Join(", ", argRefs);
    }

    private static string Pascal(string s) =>
        string.IsNullOrEmpty(s) ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);

    // -- extensions --------------------------------------------------------

    /// <summary>
    /// Nome curto sem o "I" inicial. Usado tanto pro Proxy quanto pros métodos de extensão.
    /// Ex: IInventoryService → InventoryService.
    /// </summary>
    private static string ShortNameWithoutI(ContractModel c) =>
        c.InterfaceShortName.StartsWith("I", System.StringComparison.Ordinal) &&
        c.InterfaceShortName.Length > 1
            ? c.InterfaceShortName.Substring(1)
            : c.InterfaceShortName;

    private static void EmitExtensions(StringBuilder sb, ContractModel contract)
    {
        var shortName = ShortNameWithoutI(contract);

        sb.AppendLine("/// <summary>Auto-generated registration extensions. See Rpc.SourceGen.</summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rpc.SourceGen\", \"{GeneratorVersion}\")]");
        sb.AppendLine($"public static class {shortName}RpcExtensions");
        sb.AppendLine("{");

        // 1. Add{Name}Proxy(this ProxyRegistry)
        sb.AppendLine("    /// <summary>Registra o proxy desse contrato no <see cref=\"global::Rpc.Core.ProxyRegistry\"/>.</summary>");
        sb.AppendLine($"    public static global::Rpc.Core.ProxyRegistry Add{shortName}Proxy(this global::Rpc.Core.ProxyRegistry registry)");
        sb.AppendLine("    {");
        sb.AppendLine($"        registry.Register(typeof({contract.InterfaceFullName}), static (inv, addr) => new {contract.ProxyClassName}(inv, addr));");
        sb.AppendLine("        return registry;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // 2. Add{Name}Dispatcher(this IDispatcherRegistry, T impl) — explicit impl
        sb.AppendLine("    /// <summary>Registra o dispatcher desse contrato. Aceita a implementação explicitamente.</summary>");
        sb.AppendLine($"    public static global::Rpc.Core.IDispatcherRegistry Add{shortName}Dispatcher(");
        sb.AppendLine("        this global::Rpc.Core.IDispatcherRegistry registry,");
        sb.AppendLine($"        {contract.InterfaceFullName} implementation)");
        sb.AppendLine("    {");
        sb.AppendLine($"        {contract.DispatcherClassName}.Register(registry, implementation);");
        sb.AppendLine("        return registry;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // 3. Add{Name}Dispatcher(this IDispatcherRegistry, IServiceProvider) — DI lookup
        sb.AppendLine("    /// <summary>Registra o dispatcher resolvendo a implementação via DI. Lança se não estiver registrada.</summary>");
        sb.AppendLine($"    public static global::Rpc.Core.IDispatcherRegistry Add{shortName}Dispatcher(");
        sb.AppendLine("        this global::Rpc.Core.IDispatcherRegistry registry,");
        sb.AppendLine("        global::System.IServiceProvider services)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var impl = (services.GetService(typeof({contract.InterfaceFullName})) as {contract.InterfaceFullName})");
        sb.AppendLine($"            ?? throw new global::System.InvalidOperationException(");
        sb.AppendLine($"                \"No implementation of {contract.InterfaceShortName} registered in DI.\");");
        sb.AppendLine($"        {contract.DispatcherClassName}.Register(registry, impl);");
        sb.AppendLine("        return registry;");
        sb.AppendLine("    }");

        sb.AppendLine("}");
    }
}
