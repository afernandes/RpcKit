using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Rpc.SourceGen;

/// <summary>
/// Emits a single per-assembly helper class containing <c>AddAllGeneratedProxies</c> — registra
/// todos os proxies dos contratos descobertos nesse assembly numa única chamada.
/// <para>
/// O nome da classe é derivado do nome do assembly (ex: <c>TefKit.Contracts</c> →
/// <c>TefKitContractsRpcExtensions</c>) pra evitar colisão quando vários assemblies de
/// contratos são referenciados juntos no consumidor.
/// </para>
/// </summary>
internal static class AssemblyExtensionsEmitter
{
    private const string GeneratorVersion = "1.0.0";

    public static string Emit(IReadOnlyList<ContractModel> contracts, string assemblyName)
    {
        var firstNs = contracts[0].Namespace;
        var generatedNamespace = string.IsNullOrEmpty(firstNs)
            ? "RpcGenerated"
            : firstNs + ".Generated";

        var sanitized = SanitizeAssemblyName(assemblyName);
        var className = sanitized + "RpcExtensions";
        var methodName = "AddAll" + sanitized + "Proxies";

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//     by Rpc.SourceGen v{GeneratorVersion}. Do not edit.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {generatedNamespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Aggregate helpers para os contratos descobertos no assembly <c>{assemblyName}</c>");
        sb.AppendLine($"/// ({contracts.Count} contrato{(contracts.Count == 1 ? string.Empty : "s")} ao todo).");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rpc.SourceGen\", \"{GeneratorVersion}\")]");
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");

        // AddAll{AssemblyName}Proxies
        sb.AppendLine("    /// <summary>");
        sb.AppendLine($"    /// Registra todos os {contracts.Count} proxies gerados deste assembly (<c>{assemblyName}</c>)");
        sb.AppendLine("    /// no <see cref=\"global::Rpc.Core.ProxyRegistry\"/>. O nome do método inclui o nome do assembly");
        sb.AppendLine("    /// para evitar colisão de extensões quando vários assemblies de contratos são usados juntos.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine($"    public static global::Rpc.Core.ProxyRegistry {methodName}(this global::Rpc.Core.ProxyRegistry registry)");
        sb.AppendLine("    {");
        foreach (var c in contracts.OrderBy(c => c.InterfaceShortName))
        {
            var ns = string.IsNullOrEmpty(c.Namespace) ? "RpcGenerated" : c.Namespace + ".Generated";
            sb.AppendLine($"        global::{ns}.{ShortNameWithoutI(c)}RpcExtensions.Add{ShortNameWithoutI(c)}Proxy(registry);");
        }
        sb.AppendLine("        return registry;");
        sb.AppendLine("    }");

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string ShortNameWithoutI(ContractModel c) =>
        c.InterfaceShortName.StartsWith("I", System.StringComparison.Ordinal) &&
        c.InterfaceShortName.Length > 1
            ? c.InterfaceShortName.Substring(1)
            : c.InterfaceShortName;

    /// <summary>Remove dots e caracteres inválidos do nome do assembly pra usar como identificador C#.</summary>
    private static string SanitizeAssemblyName(string assemblyName)
    {
        var sb = new StringBuilder(assemblyName.Length);
        foreach (var ch in assemblyName)
        {
            if (char.IsLetterOrDigit(ch)) sb.Append(ch);
            // dots, hyphens, etc são descartados
        }
        return sb.Length == 0 ? "Unknown" : sb.ToString();
    }
}
